def main():
    df = pd.read_csv(CSV_PATH, encoding='utf-8')

    # 그룹 컬럼 생성 (매핑에 없으면 원래 이름 유지)
    df['모델_그룹'] = df['모델'].map(MODEL_GROUP_MAP).fillna(df['모델'])

    # 매핑 안 된 모델 확인
    unmapped = df[df['모델'] == df['모델_그룹']]['모델'].unique()
    unmapped_in_map = set(MODEL_GROUP_MAP.keys())
    truly_unmapped = [m for m in unmapped if m not in unmapped_in_map]

    # 결과: 그룹별 frequency
    result = (
        df.groupby('모델_그룹')
        .size()
        .reset_index(name='frequency')
        .sort_values('frequency', ascending=False)
        .reset_index(drop=True)
    )
    result.index += 1  # 1부터 시작

    print("=" * 50)
    print(f"  모델 그룹핑 결과  |  그룹 수: {len(result)}개")
    print("=" * 50)
    print(result.to_string())

    if truly_unmapped:
        print(f"\n※ 매핑 없이 원본명 유지된 모델 ({len(truly_unmapped)}개):")
        for m in sorted(truly_unmapped):
            count = df[df['모델'] == m].shape[0]
            print(f"  - {m} ({count}건)")

    # 엑셀 저장
    output_path = r'C:\Users\Admin\hipython\ml\bermuda.project\data\model_group_frequency.xlsx'
    result.to_excel(output_path, index=True, sheet_name='모델_그룹', engine='xlsxwriter')
    print(f"\n저장 완료: {output_path}")

    return result


if __name__ == '__main__':
    result = main()
